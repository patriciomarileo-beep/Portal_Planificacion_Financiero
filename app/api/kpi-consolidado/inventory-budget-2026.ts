const normalizedBudgetBrand = (brand: string) => {
  const normalized = brand.trim().toUpperCase();
  if (normalized === "CAT") return "CATERPILLAR";
  if (normalized === "NORSEG") return "SAFETY";
  return normalized;
};

export const loadInventoryBudget = (year: number, month: number, brand: string) => {
  if (year !== 2026 || month < 1 || month > 12) return null;
  const values = inventoryBudget2026[normalizedBudgetBrand(brand)];
  if (!values) return null;
  // La planilla expresa el flujo en M$ (miles de pesos); el portal muestra MM$.
  return values[month - 1] / 1_000;
};


