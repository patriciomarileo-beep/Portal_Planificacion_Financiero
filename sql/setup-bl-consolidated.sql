-- Crea la tabla nativa mensual que consolida Real, Estimado y Proyectado B&L.
-- 2026P queda expresamente fuera de este primer alcance.
-- Los anos y el corte REAL/FORECAST se calculan dinamicamente al refrescar.
-- Este archivo no carga ni reemplaza datos.

CREATE TABLE IF NOT EXISTS
  `forus-analitica-test-datalake.silver.ft_cl_planificacion_TB_RENTABILIDAD_BL_CONSOLIDADA`
(
  PERIODO DATE NOT NULL,
  ANO INT64 NOT NULL,
  MES INT64 NOT NULL,
  ESCENARIO STRING NOT NULL,
  TIPO_DATO STRING NOT NULL,
  CC_ORIGEN STRING NOT NULL,
  CC_REPORTE STRING NOT NULL,
  CADENA STRING,
  TIENDA_ORIGEN STRING,
  TIENDA_REPORTE STRING NOT NULL,
  VENTAS FLOAT64 NOT NULL,
  MARGEN FLOAT64 NOT NULL,
  REMUNERACIONES FLOAT64 NOT NULL,
  ARRIENDOS FLOAT64 NOT NULL,
  GASTOS_GRAL FLOAT64 NOT NULL,
  DEPRECIACION FLOAT64 NOT NULL,
  FEE_COMERCIAL FLOAT64 NOT NULL,
  FEE_ADM FLOAT64 NOT NULL,
  COSTO_OPERACIONAL FLOAT64 NOT NULL,
  RESULTADO_NO_OPERACIONAL FLOAT64 NOT NULL,
  UTILIDAD_FINAL FLOAT64 NOT NULL,
  FOUR_WALLS FLOAT64,
  CLASIFICACION_RAW STRING,
  CLASIFICACION STRING NOT NULL,
  FUENTE STRING NOT NULL,
  SOURCE_SYNCED_AT TIMESTAMP,
  SYNCED_AT TIMESTAMP NOT NULL
)
PARTITION BY DATE_TRUNC(PERIODO, YEAR)
CLUSTER BY ESCENARIO, CADENA, CC_REPORTE, CLASIFICACION
OPTIONS (
  description = 'EERR mensual consolidado de tiendas B&L con escenarios R, E y P calculados dinamicamente.'
);
